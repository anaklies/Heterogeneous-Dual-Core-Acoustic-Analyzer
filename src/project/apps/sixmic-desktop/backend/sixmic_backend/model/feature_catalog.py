"""Feature catalog: 46 rows (6 spatial interfaces removed 2026-10-31) from FUNCTION_EXECUTION_MAP.csv.

The catalog is generated by interfaces/pc_backend_v1/tools/generate_feature_catalog.py
and shipped under protocol/features/. Nothing is promoted to "available" without
acceptance evidence; the loader enforces that invariant.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from ..errors import BackendError
from ..paths import protocol_dir

EXPECTED_FEATURE_COUNT = 46
VALID_STATUSES = ("available", "experimental", "not_ready", "unsupported")


class FeatureCatalog:
    def __init__(self, payload: dict[str, Any], root: Path | None = None) -> None:
        features = payload.get("features")
        if not isinstance(features, list) or len(features) != EXPECTED_FEATURE_COUNT:
            raise BackendError("schema_mismatch",
                               {"reason": "feature-catalog-count",
                                "expected": EXPECTED_FEATURE_COUNT,
                                "actual": len(features) if isinstance(features, list) else None})
        self.root = root
        self.payload = payload
        self.features: dict[str, dict[str, Any]] = {}
        for feature in features:
            feature_id = feature.get("featureId")
            if not isinstance(feature_id, str) or feature_id in self.features:
                raise BackendError("schema_mismatch", {"reason": "feature-id", "id": feature_id})
            status = feature.get("status")
            if status not in VALID_STATUSES:
                raise BackendError("schema_mismatch",
                                   {"reason": "feature-status", "id": feature_id,
                                    "status": status})
            evidence = feature.get("evidence") or {}
            if status == "available" and not (evidence.get("completeFunctionHardwareAccepted")
                                              and evidence.get("wholeBoardAccepted")):
                raise BackendError("schema_mismatch",
                                   {"reason": "available-without-acceptance-evidence",
                                    "id": feature_id})
            self.features[feature_id] = feature

    def get(self, feature_id: str) -> dict[str, Any]:
        try:
            return self.features[feature_id]
        except KeyError as exc:
            raise BackendError("bad_args", {"field": "featureId", "value": feature_id}) from exc

    def summary(self) -> dict[str, int]:
        counts = {status: 0 for status in VALID_STATUSES}
        for feature in self.features.values():
            counts[feature["status"]] += 1
        counts["total"] = len(self.features)
        return counts

    def live_available(self) -> bool:
        return any(feature["status"] == "available" for feature in self.features.values())

    def to_dict(self) -> dict[str, Any]:
        return {"catalogVersion": self.payload.get("catalogVersion", 1),
                "sourceSha256": self.payload.get("sourceSha256"),
                "summary": self.summary(),
                "features": list(self.features.values())}


_CACHE: dict[str, FeatureCatalog] = {}


def load_feature_catalog(root: str | Path | None = None) -> FeatureCatalog:
    base: Path | None = Path(root) if root else protocol_dir()
    if base is None:
        raise BackendError("file_missing", {"reason": "protocol-directory-not-found"})
    key = str(base)
    if key in _CACHE:
        return _CACHE[key]
    path = base / "features" / "FEATURE_CATALOG.json"
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise BackendError("file_missing", {"reason": "feature-catalog",
                                            "path": str(path)}) from exc
    catalog = FeatureCatalog(payload, base)
    _CACHE[key] = catalog
    return catalog
