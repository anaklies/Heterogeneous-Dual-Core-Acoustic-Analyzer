"""Generate packaging/requirements-lock.txt from the actual build venv.

Usage (Windows):
  apps/sixmic-desktop/.venv/Scripts/python.exe apps/sixmic-desktop/packaging/tools/gen_requirements_lock.py

The lock is an environment snapshot, not a curated requirements file: it pins
exactly what pip reports installed in apps/sixmic-desktop/.venv so a rebuild
uses the same versions. sixmic_backend itself is shipped source, not a PyPI
dependency, so it never appears here.

Exit codes:
  0 lock written and key packages present
  2 expected package(s) missing from the venv (nothing written unless --force)
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import platform
import subprocess
import sys
from pathlib import Path

EXPECTED_PACKAGES = ("pyside6", "pyinstaller", "pytest")
REQUIRED_FOR_BUILD = ("pyside6", "pyinstaller")


def run(cmd: list[str]) -> str:
    proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    if proc.returncode != 0:
        raise SystemExit("command failed (" + str(proc.returncode) + "): " + " ".join(cmd) + "\n" + proc.stderr.strip())
    return proc.stdout


def parse_freeze(text: str) -> dict[str, str]:
    pinned: dict[str, str] = {}
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or line.startswith("-"):
            continue
        if "==" not in line:
            continue
        name, version = line.split("==", 1)
        pinned[name.strip().lower()] = version.strip()
    return pinned


def qt_version(python: str) -> str:
    out = run(
        [
            python,
            "-c",
            "from PySide6 import QtCore; import PySide6; "
            "print(PySide6.__version__ + '|' + QtCore.qVersion())",
        ]
    ).strip()
    return out


def main(argv: list[str]) -> int:
    tools_dir = Path(__file__).resolve().parent
    packaging_dir = tools_dir.parent
    default_py = tools_dir.parents[1] / ".venv" / "Scripts" / "python.exe"
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--python", default=str(default_py), help="venv python executable")
    parser.add_argument("--output", default=str(packaging_dir / "requirements-lock.txt"))
    parser.add_argument("--allow-missing-expected", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    python = args.python
    if not Path(python).is_file():
        print("FAIL python executable not found: " + python, file=sys.stderr)
        return 2

    freeze = run([python, "-m", "pip", "freeze", "--all"])
    pinned = parse_freeze(freeze)
    expected_lower = tuple(p.lower() for p in EXPECTED_PACKAGES)
    missing = [p for p in expected_lower if p not in pinned]
    missing_required = [p for p in REQUIRED_FOR_BUILD if p not in pinned]
    if missing and not args.allow_missing_expected:
        print("FAIL expected package(s) not installed in venv: " + ", ".join(missing), file=sys.stderr)
        print("Refusing to write an incomplete lock (no fake environment snapshot).", file=sys.stderr)
        return 2
    if missing_required and not args.force:
        print("FAIL build-required package(s) missing: " + ", ".join(missing_required), file=sys.stderr)
        return 2

    py_version = run([python, "-c", "import sys; print(sys.version.split()[0])"]).strip()
    try:
        pyside = qt_version(python)
    except SystemExit:
        pyside = "unavailable"

    stamp = _dt.datetime.now(_dt.timezone.utc).astimezone()
    lines = [
        "# SixMic3D Windows packaging dependency lock (environment snapshot).",
        "# Generated by packaging/tools/gen_requirements_lock.py - do not hand-edit.",
        "#",
        "# python: " + py_version,
        "# python-executable: " + str(Path(python).resolve()),
        "# platform: " + platform.platform(),
        "# pyside6-package|qt-runtime: " + pyside,
        "# generated-local: " + stamp.isoformat(timespec="seconds"),
        "# generated-utc: " + stamp.astimezone(_dt.timezone.utc).isoformat(timespec="seconds"),
        "# expected-packages: " + ", ".join(EXPECTED_PACKAGES),
        "# check: python apps/sixmic-desktop/packaging/tools/preflight.py --mode backend",
        "#",
        "# sixmic_backend is shipped source (apps/sixmic-desktop/backend), not a PyPI package.",
        "# Rebuild (PowerShell):",
        "#   apps/sixmic-desktop/.venv/Scripts/python.exe -m pip install -r apps/sixmic-desktop/packaging/requirements-lock.txt",
        "",
    ]
    frozen_lines = freeze.strip().splitlines()
    content = "\n".join(lines + frozen_lines) + "\n"
    out = Path(args.output)
    out.write_text(content, encoding="utf-8", newline="\n")
    summary = {
        "output": str(out.resolve()),
        "python": py_version,
        "pyside6Qt": pyside,
        "pinnedCount": len(frozen_lines),
        "missingExpected": missing,
    }
    print(json.dumps(summary, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
